"""ByteTrack paper reference: Zhang et al., ECCV 2022 (https://arxiv.org/abs/2110.06864).

Task 17: reproduces every small, committed artifact from one command, using
cached detections (YOLO only re-runs on a genuine cache miss -- see
run_detect.py). Runs every stage script in dependency order and stops on the
first failure (including if any test fails, per the assignment's "do not
continue while tests fail" rule).

Usage: `python reproduce_all.py` from this directory.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

EXP_ROOT = Path(__file__).resolve().parent
PY = sys.executable

STAGES: list[list[str]] = [
    [PY, "src/clip_builder.py"],
    [PY, "build_ground_truth.py"],
    [PY, "build_projection_overlays.py"],
    [PY, "run_detect.py"],
    [PY, "build_confidence_by_visibility.py"],
    [PY, "-m", "pytest", "tests/", "-v"],
    [PY, "build_natural_events.py"],
    [PY, "build_natural_event_contact_sheets.py"],
    [PY, "build_controlled_experiments.py"],
    [PY, "build_evaluation.py"],
    [PY, "build_ablation.py"],
    [PY, "build_remaining_charts.py"],
    [PY, "build_videos.py"],
    [PY, "build_explanatory_video.py"],
]


def main() -> None:
    for stage in STAGES:
        print(f"\n=== Running: {' '.join(stage[1:])} ===")
        result = subprocess.run(stage, cwd=EXP_ROOT)
        if result.returncode != 0:
            print(f"\nSTOPPED: stage failed ({' '.join(stage[1:])}), exit code {result.returncode}.")
            sys.exit(result.returncode)

    print("\nAll stages completed. Note: build_student_experiment.py, and the "
          "student_experiment.md / student_reflection.md files it and Task 16 produce, "
          "require the student's own choices and are not regenerated by this script.")


if __name__ == "__main__":
    main()
